const dict: Record<Lang, Partial<Record<Key, string>>> = { en, ne };

interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: Key) => string;
}
const I18nContext = createContext<Ctx | null>(null);
const STORAGE = "jalrakshak-lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const s = window.localStorage.getItem(STORAGE);
    if (s === "ne" || s === "en") setLangState(s);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem(STORAGE, l);
  }, []);
  const t = useCallback((k: Key) => dict[lang][k] ?? en[k] ?? k, [lang]);
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useI18n outside provider");
  return c;
}
